/* ── 의미 그룹 적용 ────────────────────────────
   groups.js 의 스템을 긴 것부터 맞춰 g 항목을 붙인다.
   활용형(食べます·食べて·食べた…)도 같은 스템이라 자동으로 붙는다 */
(function(){
  if(!window.GROUPS) return;
  const stems=[];
  for(const g in window.GROUPS)
    window.GROUPS[g].split(/\s+/).filter(Boolean).forEach(s=>stems.push([s,g]));
  stems.sort((a,b)=>b[0].length-a[0].length);
  Object.keys(window.WORDS).forEach(k=>{
    const hit=stems.find(([s])=>k.indexOf(s)===0);
    if(hit) window.WORDS[k].g=hit[1];
  });
})();
